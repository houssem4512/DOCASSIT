"""
============================================================================
rag/vectorstore.py — Persistent Chroma vector database (zero-setup)
============================================================================
WHY THIS EXISTS
---------------
We need a place to store the chunk vectors and run similarity search against
them. Options considered:

1. pgvector  — best for production but requires Postgres (the project ships
               with SQLite). Adds operational burden.
2. FAISS     — in-memory only; we'd have to manage save/load ourselves.
3. Chroma    — persistent client backed by a local folder. Zero setup,
               good enough for the project scale (~thousands of chunks),
               integrates natively with LangChain via `langchain-chroma`.

We picked Chroma. The DB lives at `settings.CHROMA_DIR` (`backend/chroma_db/`).
Add `chroma_db/` to `.gitignore` — it's a build artifact, not source.

COLLECTION SCHEMA
-----------------
Collection name: "docs"
Each document stored as:
    id:           auto-generated by Chroma
    embedding:    384-dim float vector (from `rag/embeddings.py`)
    document:     chunk text (Chroma's `document` field — searchable)
    metadata:     {doc_id, language, title, source_page, chunk_index}

The `language` metadata field is what powers `search_by_language` in the MCP
server and the language filter in the Search page UI.
"""
from __future__ import annotations

from django.conf import settings
from langchain_chroma import Chroma

import chromadb

_COLLECTION = "docs"

# Single persistent client per process. `chromadb.PersistentClient` keeps
# the DB on disk; restarts are safe — vectors survive.
_client: chromadb.api.ClientAPI | None = None


def _get_client():
    """Lazy-init the Chroma persistent client."""
    global _client
    if _client is None:
        _client = chromadb.PersistentClient(path=settings.CHROMA_DIR)
    return _client


def get_store() -> Chroma:
    """
    Return the LangChain `Chroma` vector store bound to our embeddings.

    Used by:
    - `rag/my_engine.py`        → ingest, delete, search, retrieve-for-answer
    - `rag/chain.py`            → as_retriever() for the LangChain RAG chain
    - `rag/graph.py`            → similarity_search in the retrieve node
    - `mcp_server/server.py`    → all 3 MCP tools
    """
    from .embeddings import get_embeddings
    return Chroma(
        collection_name=_COLLECTION,
        embedding_function=get_embeddings(),
        client=_get_client(),
    )


def reset_store() -> None:
    """
    Nuclear option: drop the entire collection. Used by the `seed_demo`
    management command and by `bench/run_all.sh` to start benchmarks clean.
    """
    try:
        _get_client().delete_collection(_COLLECTION)
    except Exception:
        pass  # collection doesn't exist yet — fine


def count() -> int:
    """How many chunks are indexed. Surfaced in the admin health endpoint."""
    try:
        return get_store()._collection.count()
    except Exception:
        return 0
